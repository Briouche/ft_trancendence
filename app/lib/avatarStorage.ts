import "server-only";

import { randomUUID } from "crypto";
import { mkdir, readFile, unlink, writeFile } from "fs/promises";
import path from "path";

// Avatar files on disk. They live outside the web root (a Docker volume, AVATAR_DIR) and are only
// ever served by app/api/avatars/[file]/route.ts, with a Content-Type chosen by the server, so an
// uploaded file can never be executed or interpreted as anything but an image.

export const AVATAR_MAX_BYTES = 2 * 1024 * 1024;

/** Where avatars are stored: a Docker volume in the containers, ./uploads/avatars otherwise. */
export const AVATAR_DIR = process.env.AVATAR_DIR ?? path.join(process.cwd(), "uploads", "avatars");

export type AvatarFormat = { ext: "png" | "jpg" | "webp"; mime: string };

const FORMATS: Record<AvatarFormat["ext"], AvatarFormat> = {
  png: { ext: "png", mime: "image/png" },
  jpg: { ext: "jpg", mime: "image/jpeg" },
  webp: { ext: "webp", mime: "image/webp" },
};

/**
 * Image format from the file's first bytes ("magic numbers"). The browser-provided file name and
 * MIME type are ignored on purpose: both are chosen by the client and trivial to fake.
 */
export function detectImageFormat(bytes: Uint8Array): AvatarFormat | null {
  const starts = (sig: number[], offset = 0) => sig.every((b, i) => bytes[offset + i] === b);

  if (starts([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a])) return FORMATS.png;
  if (starts([0xff, 0xd8, 0xff])) return FORMATS.jpg;
  // RIFF....WEBP
  if (starts([0x52, 0x49, 0x46, 0x46]) && starts([0x57, 0x45, 0x42, 0x50], 8)) return FORMATS.webp;
  return null;
}

// Names are generated by saveAvatar only: "<userId>-<uuid>.<ext>". Anything else is rejected
// before touching the file system, which also rules out path traversal ("../../etc/passwd").
const AVATAR_NAME = /^\d+-[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.(png|jpg|webp)$/;

/** True for a file name saveAvatar could have produced. */
export function isAvatarFileName(name: string): boolean {
  return AVATAR_NAME.test(name);
}

/** MIME type to serve a stored avatar with (from its extension, which the server chose). */
export function avatarMime(name: string): string {
  return FORMATS[name.slice(name.lastIndexOf(".") + 1) as AvatarFormat["ext"]].mime;
}

/** Writes an avatar under a fresh random name and returns that name. */
export async function saveAvatar(userId: number, bytes: Uint8Array, format: AvatarFormat): Promise<string> {
  await mkdir(AVATAR_DIR, { recursive: true });
  const name = `${userId}-${randomUUID()}.${format.ext}`;
  await writeFile(path.join(AVATAR_DIR, name), bytes, { mode: 0o644 });
  return name;
}

/** Reads a stored avatar, or null if the name is invalid or the file doesn't exist. */
export async function readAvatar(name: string): Promise<Buffer | null> {
  if (!isAvatarFileName(name)) return null;
  return readFile(path.join(AVATAR_DIR, name)).catch(() => null);
}

/** Deletes a stored avatar (ignores invalid names and missing files). */
export async function deleteAvatar(name: string | null): Promise<void> {
  if (!name || !isAvatarFileName(name)) return;
  await unlink(path.join(AVATAR_DIR, name)).catch(() => undefined);
}
