import { describe, expect, it } from "vitest";
import { avatarMime, detectImageFormat, isAvatarFileName } from "@/lib/avatarStorage";

const bytes = (...values: number[]) => new Uint8Array([...values, ...new Array(16).fill(0)]);

describe("detectImageFormat", () => {
  it("recognises PNG, JPEG and WebP by their magic bytes", () => {
    expect(detectImageFormat(bytes(0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a))?.ext).toBe("png");
    expect(detectImageFormat(bytes(0xff, 0xd8, 0xff, 0xe0))?.ext).toBe("jpg");
    expect(detectImageFormat(bytes(0x52, 0x49, 0x46, 0x46, 1, 2, 3, 4, 0x57, 0x45, 0x42, 0x50))?.ext).toBe("webp");
  });

  it("rejects anything else, whatever its name or declared type", () => {
    expect(detectImageFormat(new TextEncoder().encode("<svg onload=alert(1)>"))).toBeNull();
    expect(detectImageFormat(new TextEncoder().encode("<?php system($_GET['c']); ?>"))).toBeNull();
    expect(detectImageFormat(bytes(0x47, 0x49, 0x46, 0x38))).toBeNull(); // GIF
    // RIFF but not WEBP (e.g. a WAV file)
    expect(detectImageFormat(bytes(0x52, 0x49, 0x46, 0x46, 1, 2, 3, 4, 0x57, 0x41, 0x56, 0x45))).toBeNull();
  });
});

describe("isAvatarFileName", () => {
  it("only accepts names generated by saveAvatar", () => {
    expect(isAvatarFileName("12-0f8fad5b-d9cb-469f-a165-70867728950e.png")).toBe(true);
    expect(isAvatarFileName("../../etc/passwd")).toBe(false);
    expect(isAvatarFileName("12-0f8fad5b-d9cb-469f-a165-70867728950e.svg")).toBe(false);
    expect(isAvatarFileName("12-0f8fad5b-d9cb-469f-a165-70867728950e.png/../x")).toBe(false);
    expect(isAvatarFileName("evil.html")).toBe(false);
  });

  it("serves each stored format with its own MIME type", () => {
    expect(avatarMime("1-0f8fad5b-d9cb-469f-a165-70867728950e.webp")).toBe("image/webp");
    expect(avatarMime("1-0f8fad5b-d9cb-469f-a165-70867728950e.jpg")).toBe("image/jpeg");
  });
});
